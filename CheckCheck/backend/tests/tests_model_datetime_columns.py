"""Every timestamp column stores naive UTC (no HTTP, imports the models directly).

Since sqlmodel 0.0.45 a field annotated with a bare ``datetime`` becomes
sqlmodel's tz-aware ``UTCDateTime`` column (``timestamptz`` on Postgres), which
raises on the first naive value written to it. The project stores naive UTC
everywhere (``naive_utc_now()``), so such a field breaks inserts and would show
up as a type change in an autogenerated migration. Timestamp columns are declared
as pydantic's ``NaiveDatetime`` instead; this test catches a new column that
forgot to, even when no other test happens to write it.
"""

import sqlalchemy as sa
from sqlmodel import SQLModel, UTCDateTime

import checkcheckserver.model._tables  # noqa: F401  (registers every table)


def _timestamp_columns():
    for table in SQLModel.metadata.tables.values():
        for column in table.columns:
            if isinstance(column.type, (sa.DateTime, UTCDateTime)):
                yield f"{table.name}.{column.name}", column.type


def test_there_are_timestamp_columns_to_check():
    # Guards the test itself: an empty registry would make the next one vacuous.
    assert len(list(_timestamp_columns())) > 20


def test_no_timestamp_column_is_timezone_aware():
    offenders = [
        f"{name} ({type(col_type).__name__})"
        for name, col_type in _timestamp_columns()
        if isinstance(col_type, UTCDateTime) or col_type.timezone
    ]
    assert not offenders, (
        "These timestamp columns are tz-aware; declare them as pydantic's "
        f"NaiveDatetime instead of a bare datetime: {offenders}"
    )
